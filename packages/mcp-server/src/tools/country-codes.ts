const COUNTRY_CODE_SET: ReadonlySet<string> = new Set(COUNTRY_CODES);

/** Upper-cased alpha-3 code accepted by upstream, or `null` when not a known code. */
export function normalizeCountryCode(value: string): string | null {
  const code = value.trim().toUpperCase();
  return COUNTRY_CODE_SET.has(code) ? code : null;
}

/** A `CountryCode` input: any case on the way in, validated against the enum. */
export const countryCodeInput = z
  .string()
  .transform(value => value.trim().toUpperCase())
  .pipe(
    z.string().refine(value => COUNTRY_CODE_SET.has(value), {
      message: 'must be an ISO 3166-1 alpha-3 country code known to Accounter, e.g. ISR, USA, DEU',
    }),
  );

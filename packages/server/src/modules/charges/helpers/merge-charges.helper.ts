import { GraphQLError } from 'graphql';
import { Injector } from 'graphql-modules';
import { BusinessTripEmployeePaymentsProvider } from '../../business-trips/providers/business-trips-employee-payments.provider.js';
import { DocumentsProvider } from '../../documents/providers/documents.provider.js';
import { SecurityExecutionChargesProvider } from '../../foreign-securities/providers/security-execution-charges.provider.js';
import { LedgerProvider } from '../../ledger/providers/ledger.provider.js';
import { MiscExpensesProvider } from '../../misc-expenses/providers/misc-expenses.provider.js';
import { TransactionsProvider } from '../../transactions/providers/transactions.provider.js';
import { ChargesProvider } from '../providers/charges.provider.js';
import { deleteCharges } from './delete-charges.helper.js';

async function ensureSecuritiesChargeType(chargeId: string, injector: Injector) {
  const linkedExecutionIds = await injector
    .get(SecurityExecutionChargesProvider)
    .linkedExecutionIdsByChargeIdLoader.load(chargeId);
  if (linkedExecutionIds.length === 0) {
    return;
  }
  const charge = await injector.get(ChargesProvider).getChargeByIdLoader.load(chargeId);
  if (charge && charge.type !== 'FOREIGN_SECURITIES') {
    await injector.get(ChargesProvider).updateCharge({ chargeId, type: 'FOREIGN_SECURITIES' });
  }
}

export const mergeChargesExecutor = async (
  chargeIdsToMerge: readonly string[],
  baseChargeID: string,
  injector: Injector,
) => {
  try {
    const chargeCleaner = chargeIdsToMerge.map(id => {
      // update linked documents
      const replaceDocumentsChargeIdPromise = injector
        .get(DocumentsProvider)
        .replaceDocumentsChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      // update linked transactions
      const replaceTransactionsChargeIdPromise = injector
        .get(TransactionsProvider)
        .replaceTransactionsChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      // update linked ledger records
      const replaceLedgerRecordsChargeIdPromise = injector
        .get(LedgerProvider)
        .replaceLedgerRecordsChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      // update linked misc expenses
      const replaceMiscExpensesChargeIdPromise = injector
        .get(MiscExpensesProvider)
        .replaceMiscExpensesChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      // update linked business trips employee payments
      const replaceBusinessTripsEmployeePaymentsChargeIdPromise = injector
        .get(BusinessTripEmployeePaymentsProvider)
        .replaceBusinessTripsEmployeePaymentsChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      // update linked securities executions
      const replaceSecurityExecutionsChargeIdPromise = injector
        .get(SecurityExecutionChargesProvider)
        .replaceChargeId({
          replaceChargeID: id,
          assertChargeID: baseChargeID,
        });

      return Promise.all([
        replaceDocumentsChargeIdPromise,
        replaceTransactionsChargeIdPromise,
        replaceLedgerRecordsChargeIdPromise,
        replaceMiscExpensesChargeIdPromise,
        replaceBusinessTripsEmployeePaymentsChargeIdPromise,
        replaceSecurityExecutionsChargeIdPromise,
      ]);
    });

    await Promise.all(chargeCleaner);

    // Securities executions booked directly are generated by the securities ledger only; a base
    // charge typed otherwise (say, the bank fee a distribution's commission landed in) would
    // silently drop them.
    await ensureSecuritiesChargeType(baseChargeID, injector);

    // delete charge
    await deleteCharges([...chargeIdsToMerge], injector);
  } catch (e) {
    if (e instanceof GraphQLError) {
      throw e;
    }
    throw new GraphQLError(`Failed to merge charges: ${e}`);
  }
};

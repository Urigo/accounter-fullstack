/**
 * Golden files (SPEC §13.5): every tests/fixtures/golden/<name>.input.ts generates exactly the
 * committed <name>.opcn, whose sha256 is recorded in VERIFICATION.md. UPDATE_GOLDEN=1 rewrites the
 * .opcn files instead (see tests/fixtures/golden/README.md).
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import {
  generate1214,
  validate1214,
  type GenerateOptions,
  type Report1214Input,
} from '../../src/index.js';

const GOLDEN_DIR = new URL('../fixtures/golden/', import.meta.url);
const INPUT_SUFFIX = '.input.ts';
const UPDATE = process.env['UPDATE_GOLDEN'] === '1';

interface GoldenFixture {
  input: Report1214Input;
  options: GenerateOptions;
}

const fixtureNames = readdirSync(GOLDEN_DIR)
  .filter(file => file.endsWith(INPUT_SUFFIX))
  .map(file => file.slice(0, -INPUT_SUFFIX.length))
  .sort();

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

/** Fixture name → sha256, from the table of VERIFICATION.md. */
function verifiedHashes(): Map<string, string> {
  const table = readFileSync(new URL('VERIFICATION.md', GOLDEN_DIR), 'utf8');
  const hashes = new Map<string, string>();
  for (const line of table.split('\n')) {
    const cells = line
      .split('|')
      .slice(1, -1)
      .map(cell => cell.trim().replaceAll('`', ''));
    const [fixture, hash] = cells;
    if (cells.length === 5 && fixture && hash && /^[0-9a-f]{64}$/.test(hash)) {
      hashes.set(fixture, hash);
    }
  }
  return hashes;
}

describe('golden files', () => {
  it('has at least one fixture, each listed in VERIFICATION.md, and no orphan rows', () => {
    expect(fixtureNames.length).toBeGreaterThan(0);
    expect([...verifiedHashes().keys()].sort()).toEqual(fixtureNames);
  });

  it.each(fixtureNames)('%s input validates with zero errors', async name => {
    const { input, options } = (await import(
      new URL(`${name}${INPUT_SUFFIX}`, GOLDEN_DIR).href
    )) as GoldenFixture;
    expect(validate1214(input, options).errors).toEqual([]);
  });

  it.each(fixtureNames)('%s.opcn is generated byte for byte', async name => {
    const { input, options } = (await import(
      new URL(`${name}${INPUT_SUFFIX}`, GOLDEN_DIR).href
    )) as GoldenFixture;
    const goldenUrl = new URL(`${name}.opcn`, GOLDEN_DIR);
    const { bytes } = generate1214(input, options);
    if (UPDATE) {
      writeFileSync(goldenUrl, bytes);
    }
    expect(existsSync(goldenUrl), `${name}.opcn is missing: run with UPDATE_GOLDEN=1`).toBe(true);
    const golden = new Uint8Array(readFileSync(goldenUrl));
    expect(Buffer.from(bytes).equals(Buffer.from(golden)), `${name}.opcn differs`).toBe(true);
    expect(sha256(golden), `sha256 of ${name}.opcn vs VERIFICATION.md`).toBe(
      verifiedHashes().get(name),
    );
  });
});
